def normalize_language(language: str) -> str:
    lang = (language or DEFAULT_LANGUAGE).lower()[:2]
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, language: str = DEFAULT_LANGUAGE, **kwargs) -> str:
    lang = normalize_language(language)
    table = STRINGS[lang]
    text = table.get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**kwargs) if kwargs else text


def missing_keys() -> Dict[str, list]:
    """Keys present in one language but not the other (used by tests)."""
    de, en = set(STRINGS["de"]), set(STRINGS["en"])
    return {"missing_in_en": sorted(de - en), "missing_in_de": sorted(en - de)}
